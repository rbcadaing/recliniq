from alembic.script import ScriptDirectory
from httpx import AsyncClient
from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncEngine, AsyncSession

from alembic import command
from tests.integration.conftest import alembic_config, transactional_session


def test_migrations_upgrade_from_empty_and_downgrade(migrated_database: str) -> None:
    config = alembic_config(migrated_database)
    command.downgrade(config, "base")
    command.upgrade(config, "head")


def test_single_migration_head(migrated_database: str) -> None:
    script = ScriptDirectory.from_config(alembic_config(migrated_database))
    assert len(script.get_heads()) == 1, "multiple Alembic heads: merge them"


def test_models_and_migrations_are_in_sync(migrated_database: str) -> None:
    # Raises AutogenerateDiffsDetected if ORM models define changes no migration captures.
    command.check(alembic_config(migrated_database))


async def test_db_session_executes_queries(db_session: AsyncSession) -> None:
    result = await db_session.execute(text("SELECT 1"))
    assert result.scalar_one() == 1


async def test_transactional_session_rolls_back(engine: AsyncEngine) -> None:
    async with transactional_session(engine) as session:
        await session.execute(text("CREATE TABLE isolation_probe (id int)"))
        await session.commit()  # becomes a savepoint release, still rolled back on exit

    async with engine.connect() as connection:
        exists = await connection.scalar(text("SELECT to_regclass('public.isolation_probe')"))
    assert exists is None


async def test_readiness_with_real_database(integration_client: AsyncClient) -> None:
    response = await integration_client.get("/api/v1/health/ready")
    assert response.status_code == 200
    assert response.json() == {"status": "ok", "checks": {"database": "ok"}}
