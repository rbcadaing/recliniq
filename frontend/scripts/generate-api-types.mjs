#!/usr/bin/env node
// Generates src/api/generated/schema.ts from the committed OpenAPI snapshot (US-00.4).
//
//   npm run api:generate
//
// Output mirrors openapi-typescript's `components['schemas'][Name]` shape, so API modules alias
// generated types instead of hand-writing them. We use this small dependency-free generator
// because openapi-typescript 7 needs the TypeScript 5 JS compiler API (gone in TypeScript 7)
// and openapi-typescript 6 fails `npm audit` (undici@5). See docs/ci.md → "API contract".
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
export const SNAPSHOT_PATH = resolve(HERE, '../src/api/generated/openapi.json')
export const OUTPUT_PATH = resolve(HERE, '../src/api/generated/schema.ts')

const REF_PREFIX = '#/components/schemas/'
const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/

const indent = (depth) => '  '.repeat(depth)
const key = (name) => (IDENTIFIER.test(name) ? name : JSON.stringify(name))
const union = (parts) => {
  const unique = [...new Set(parts)]
  return unique.length === 0 ? 'never' : unique.join(' | ')
}
const wrap = (type) => (/[|&]/.test(type) ? `(${type})` : type)

/** Converts one JSON Schema node (OpenAPI 3.1 dialect) into a TypeScript type expression. */
export function toType(schema, depth = 0) {
  if (schema === true || schema === undefined || schema === null) return 'unknown'
  if (schema === false) return 'never'
  if (schema.$ref) {
    if (!schema.$ref.startsWith(REF_PREFIX)) throw new Error(`Unsupported $ref: ${schema.$ref}`)
    return `components['schemas']['${schema.$ref.slice(REF_PREFIX.length)}']`
  }
  if ('const' in schema) return JSON.stringify(schema.const)
  if (schema.enum) return union(schema.enum.map((value) => JSON.stringify(value)))
  if (schema.anyOf || schema.oneOf) {
    return union((schema.anyOf ?? schema.oneOf).map((part) => toType(part, depth)))
  }
  if (schema.allOf) return schema.allOf.map((part) => wrap(toType(part, depth))).join(' & ')

  const types = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : []
  if (types.length === 0) return schema.properties ? objectType(schema, depth) : 'unknown'
  return union(types.map((type) => primitive(type, schema, depth)))
}

function primitive(type, schema, depth) {
  switch (type) {
    case 'string':
      return 'string'
    case 'integer':
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'null':
      return 'null'
    case 'array':
      return `${wrap(toType(schema.items, depth))}[]`
    case 'object':
      return objectType(schema, depth)
    default:
      throw new Error(`Unsupported schema type: ${type}`)
  }
}

function objectType(schema, depth) {
  const properties = Object.entries(schema.properties ?? {})
  const extra = schema.additionalProperties
  if (properties.length === 0) {
    return extra && extra !== true
      ? `Record<string, ${toType(extra, depth)}>`
      : 'Record<string, unknown>'
  }
  const required = new Set(schema.required ?? [])
  const lines = properties.map(([name, property]) => {
    const optional = required.has(name) ? '' : '?'
    return `${indent(depth + 1)}${key(name)}${optional}: ${toType(property, depth + 1)}`
  })
  if (extra)
    lines.push(
      `${indent(depth + 1)}[key: string]: ${extra === true ? 'unknown' : toType(extra, depth + 1)}`,
    )
  return `{\n${lines.join('\n')}\n${indent(depth)}}`
}

/** Renders the whole module for an OpenAPI document. Deterministic: schemas are sorted by name. */
export function render(document) {
  const schemas = Object.entries(document.components?.schemas ?? {}).sort(([a], [b]) =>
    a < b ? -1 : a > b ? 1 : 0,
  )
  const body = schemas.map(([name, schema]) => `    ${key(name)}: ${toType(schema, 2)}`).join('\n')
  return [
    '// Generated by scripts/generate-api-types.mjs from openapi.json. Do not edit by hand.',
    '// Regenerate: `cd backend && uv run python -m scripts.export_openapi`, then',
    '// `cd frontend && npm run api:generate`.',
    '',
    'export interface components {',
    '  schemas: {',
    body,
    '  }',
    '}',
    '',
  ].join('\n')
}

function main() {
  const document = JSON.parse(readFileSync(SNAPSHOT_PATH, 'utf8'))
  writeFileSync(OUTPUT_PATH, render(document))
  console.log(`Wrote ${OUTPUT_PATH}`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
